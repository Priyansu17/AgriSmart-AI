/**
 * Returns localized name, category, and agronomic info for any crop.
 */
export function getLocalizedCropData(cropKey, lang = 'en') {
  const cleanKey = String(cropKey || '').trim().toLowerCase().replace(/[^a-z]/g, '');
  const detailed = CROP_LOCALIZATIONS[cleanKey];
  const lookup = CROP_NAME_LOOKUP[cleanKey];

  const safeLang = ['en', 'hi', 'pa', 'mr', 'te', 'ta', 'bn', 'gu'].includes(lang) ? lang : 'en';

  const localizedName = (detailed?.name?.[safeLang]) || (lookup?.[safeLang]) || (cropKey ? (cropKey.charAt(0).toUpperCase() + cropKey.slice(1)) : 'Crop');
  const localizedCategory = (detailed?.category?.[safeLang]) || null;
  const localizedDesc = (detailed?.description?.[safeLang]) || null;
  const localizedSeason = (detailed?.season?.[safeLang]) || null;
  const localizedSoil = (detailed?.soil?.[safeLang]) || null;
  const localizedWater = (detailed?.water?.[safeLang]) || null;
  const localizedClimate = (detailed?.climate?.[safeLang]) || null;

  return {
    name: localizedName,
    category: localizedCategory,
    description: localizedDesc,
    season: localizedSeason,
    soil: localizedSoil,
    water: localizedWater,
    climate: localizedClimate
  };
}

